#!/usr/bin/env python3
"""Render the preset and theme galleries from demo data.

Writes, deterministically (fixed ``demo.NOW``, fixed widths):

* ``docs/assets/presets/<preset>.svg`` - every preset with the ``default`` theme
* ``docs/assets/themes/<theme>.svg``   - the ``default`` preset in every theme
* ``docs/assets/hero.svg``             - the README hero image
* ``docs/presets.md`` and ``docs/themes.md`` - the gallery pages

Usage::

    uv run python scripts/render_screenshots.py           # regenerate everything
    uv run python scripts/render_screenshots.py --check   # exit 1 if anything is stale
    uv run python scripts/render_screenshots.py --print   # show the ANSI output instead

``rich`` (a docs-only dev dependency) turns the ANSI text into SVG.
"""

from __future__ import annotations

import argparse
import io
import sys
from dataclasses import dataclass
from pathlib import Path

from rich.console import Console
from rich.terminal_theme import TerminalTheme
from rich.text import Text

from pihello import demo, presets, themes
from pihello.template import ColorDepth, RenderOptions, Template

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
ASSETS = DOCS / "assets"
GENERATED_NOTE = (
    "<!-- Generated by scripts/render_screenshots.py from demo data; do not edit by hand.\n"
    "     Run `uv run python scripts/render_screenshots.py` after changing a preset or theme. -->"
)

# A neutral dark terminal (VS Code's integrated terminal palette) for the
# preset gallery; theme screenshots use their palette's own background.
_VSCODE_NORMAL = [
    (0x00, 0x00, 0x00),
    (0xCD, 0x31, 0x31),
    (0x0D, 0xBC, 0x79),
    (0xE5, 0xE5, 0x10),
    (0x24, 0x72, 0xC8),
    (0xBC, 0x3F, 0xBC),
    (0x11, 0xA8, 0xCD),
    (0xE5, 0xE5, 0xE5),
]
_VSCODE_BRIGHT = [
    (0x66, 0x66, 0x66),
    (0xF1, 0x4C, 0x4C),
    (0x23, 0xD1, 0x8B),
    (0xF5, 0xF5, 0x43),
    (0x3B, 0x8E, 0xEA),
    (0xD6, 0x70, 0xD6),
    (0x29, 0xB8, 0xDB),
    (0xFF, 0xFF, 0xFF),
]


def _hex(value: str) -> tuple[int, int, int]:
    value = value.lstrip("#")
    return (int(value[0:2], 16), int(value[2:4], 16), int(value[4:6], 16))


def _terminal(background: str, foreground: str) -> TerminalTheme:
    return TerminalTheme(_hex(background), _hex(foreground), _VSCODE_NORMAL, _VSCODE_BRIGHT)


DARK = _terminal("#16181d", "#d4d4d4")
#: Background/foreground of each theme's native palette (official values).
THEME_TERMINALS: dict[str, TerminalTheme] = {
    "nord": _terminal("#2E3440", "#D8DEE9"),
    "dracula": _terminal("#282A36", "#F8F8F2"),
    "gruvbox": _terminal("#282828", "#EBDBB2"),
    "catppuccin": _terminal("#1E1E2E", "#CDD6F4"),
    "solarized": _terminal("#002B36", "#839496"),
    "tokyonight": _terminal("#1A1B26", "#C0CAF5"),
    "monokai": _terminal("#272822", "#F8F8F2"),
}


@dataclass(frozen=True)
class Shot:
    """One screenshot: where it goes, what it shows and how it is framed."""

    path: Path
    title: str
    ansi: str
    width: int
    terminal: TerminalTheme


def render(preset: presets.Preset, theme: str = "default") -> str:
    """Render ``preset`` with demo data as truecolor ANSI text."""
    template = Template.parse(preset.source, name=f"preset:{preset.name}")
    options = RenderOptions(color=ColorDepth.TRUECOLOR, strict=True, now=demo.NOW)
    return template.render(demo.variables(), theme=themes.resolve(theme), options=options)


def to_svg(shot: Shot) -> str:
    """Convert the ANSI text of ``shot`` into a self-contained SVG document."""
    console = Console(
        record=True,
        width=shot.width,
        force_terminal=True,
        color_system="truecolor",
        file=io.StringIO(),
        legacy_windows=False,
        _environ={},
    )
    console.print(Text.from_ansi(shot.ansi), soft_wrap=True)
    return console.export_svg(title=shot.title, theme=shot.terminal)


def shots() -> list[Shot]:
    """Every screenshot of the galleries plus the hero image."""
    result: list[Shot] = []
    for preset in presets.available():
        result.append(
            Shot(
                path=ASSETS / "presets" / f"{preset.name}.svg",
                title=f"pihello --preset {preset.name}",
                ansi=render(preset),
                width=max(preset.min_width + 2, 40),
                terminal=DARK,
            )
        )
    default = presets.get("default")
    for theme in themes.available():
        result.append(
            Shot(
                path=ASSETS / "themes" / f"{theme.name}.svg",
                title=f"pihello --theme {theme.name}",
                ansi=render(default, theme.name),
                width=default.min_width + 2,
                terminal=THEME_TERMINALS.get(theme.name, DARK),
            )
        )
    prompt = "\x1b[1;38;2;80;250;123m~\x1b[0m \x1b[38;2;189;147;249m\u276f\x1b[0m "
    result.append(
        Shot(
            path=ASSETS / "hero.svg",
            title="pihello",
            ansi=f"{prompt}pihello\n{render(default)}\n\n{prompt}pihello --preset status\n"
            + render(presets.get("status")),
            width=default.min_width + 2,
            terminal=DARK,
        )
    )
    return result


def _details(source: str) -> str:
    fence = "````" if "```" in source else "```"
    return (
        "<details>\n<summary>Template source</summary>\n\n"
        f"{fence}text\n{source.rstrip()}\n{fence}\n\n</details>\n"
    )


def presets_page() -> str:
    """The Markdown of ``docs/presets.md``."""
    out = [
        "# Presets",
        "",
        GENERATED_NOTE,
        "",
        "A preset is a built-in template. Choose one with `--preset NAME` (or",
        '`preset = "NAME"` in the config file) and combine it with any',
        "[theme](themes.md). `pihello presets` previews them all in your terminal",
        "with demo data (`--live` uses your Pi-hole's data instead).",
        "",
        "To make your own, start from a preset and point the config at the file",
        "(the template language is described in [templates.md](templates.md)):",
        "",
        "```sh",
        "pihello presets default --source > ~/.config/pihello/greeting.txt",
        '# config.toml: template = "~/.config/pihello/greeting.txt"',
        "```",
        "",
        "Every preset except `classic` uses the semantic theme styles, so it works",
        "with every theme. *Min width* is the widest line rendered from demo data;",
        'narrower terminals wrap (or clip with `overflow = "clip"`).',
        "",
        "| Preset | Description | Min width |",
        "| :-- | :-- | --: |",
    ]
    out += [
        f"| [`{p.name}`](#{p.name}) | {p.description} | {p.min_width} |"
        for p in presets.available()
    ]
    for preset in presets.available():
        out += [
            "",
            f"## {preset.name}",
            "",
            f"{preset.description[0].upper()}{preset.description[1:]}.",
            "",
            f"![{preset.name} preset](assets/presets/{preset.name}.svg)",
            "",
            "```sh",
            f"pihello --preset {preset.name}",
            "```",
            "",
            f"Minimum width: **{preset.min_width}** columns.",
            "",
            _details(preset.source),
        ]
    return "\n".join(out).rstrip("\n") + "\n"


def themes_page() -> str:
    """The Markdown of ``docs/themes.md``."""
    out = [
        "# Themes",
        "",
        GENERATED_NOTE,
        "",
        "A theme maps the semantic style names used by the presets to concrete",
        'styles. Choose one with `--theme NAME` (or `theme = "NAME"` in the config',
        "file); `pihello themes` previews them all in your own terminal (try",
        "`pihello themes nord --preset dashboard`). Colors are",
        "automatically downgraded to 256 or 16 colors when the terminal needs it.",
        "",
        "| Theme | Description |",
        "| :-- | :-- |",
    ]
    out += [f"| [`{t.name}`](#{t.name}) | {t.description} |" for t in themes.available()]
    out += [
        "",
        "## Style names",
        "",
        "| Style | Used for |",
        "| :-- | :-- |",
        '| `title` | the main heading ("Pi-hole") |',
        "| `subtitle` | secondary headings: section names, the host name |",
        "| `border` | rules, box frames and separators |",
        '| `label` | field labels ("Queries", "Gravity") |',
        "| `value` | ordinary values |",
        '| `muted` | de-emphasised text: units, "ago", hints |',
        "| `accent` | key numbers: total queries, active clients |",
        "| `good` | healthy state: blocking enabled, up to date |",
        "| `warn` | attention: updates available, disable timers |",
        "| `bad` | failure: blocking disabled, errors |",
        "| `info` | informational numbers: gravity size, upstreams |",
        "| `highlight` | blocked things: blocked count, percentage, domains |",
        "",
        "Use them in your own templates as `[@label]Queries [@value]{queries.total|number}`.",
        "",
        "## Overriding styles",
        "",
        "Any style of the selected theme can be replaced in the `[styles]` table of",
        "the config file. Values are style-tag words (see `pihello colors` for the",
        "color names) and may refer to the theme's own styles with `@name`:",
        "",
        "```toml",
        'theme = "nord"',
        "",
        "[styles]",
        'accent = "bold #ff8800"',
        'highlight = "@bad underline"',
        "```",
    ]
    for theme in themes.available():
        out += [
            "",
            f"## {theme.name}",
            "",
            f"{theme.description[0].upper()}{theme.description[1:]}.",
            "",
            f"![{theme.name} theme](assets/themes/{theme.name}.svg)",
            "",
            "```sh",
            f"pihello --theme {theme.name}",
            "```",
            "",
            "<details>\n<summary>Styles</summary>\n",
            "| Style | Words |",
            "| :-- | :-- |",
        ]
        out += [f"| `{name}` | `{words}` |" for name, words in theme.styles.items()]
        out += ["", "</details>"]
    return "\n".join(out).rstrip("\n") + "\n"


def outputs() -> dict[Path, str]:
    """Every generated file and its expected content."""
    files = {shot.path: to_svg(shot) for shot in shots()}
    files[DOCS / "presets.md"] = presets_page()
    files[DOCS / "themes.md"] = themes_page()
    return files


def _stale_assets(expected: dict[Path, str]) -> list[Path]:
    """SVGs in the gallery folders that no preset/theme produces anymore."""
    found = [*ASSETS.glob("presets/*.svg"), *ASSETS.glob("themes/*.svg")]
    return sorted(path for path in found if path not in expected)


def main(argv: list[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if generated files are stale")
    mode.add_argument("--print", action="store_true", help="print the ANSI renderings")
    args = parser.parse_args(argv)

    if args.print:
        for shot in shots():
            sys.stdout.write(f"\n=== {shot.title} ({shot.path.name}, {shot.width} cols)\n")
            sys.stdout.write(shot.ansi + "\n")
        return 0

    expected = outputs()
    if args.check:
        stale = [
            path
            for path, content in expected.items()
            if not path.exists() or path.read_text(encoding="utf-8") != content
        ]
        stale += _stale_assets(expected)
        for path in stale:
            sys.stderr.write(f"stale: {path.relative_to(ROOT)}\n")
        if stale:
            sys.stderr.write("run: uv run python scripts/render_screenshots.py\n")
            return 1
        return 0

    for path in _stale_assets(expected):
        path.unlink()
        sys.stdout.write(f"removed {path.relative_to(ROOT)}\n")
    for path, content in expected.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        if not path.exists() or path.read_text(encoding="utf-8") != content:
            path.write_text(content, encoding="utf-8", newline="\n")
            sys.stdout.write(f"wrote {path.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
