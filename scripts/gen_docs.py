#!/usr/bin/env python3
"""Generate the reference parts of the documentation from the code.

Writes, deterministically:

* ``docs/variables.md`` - every template variable from ``pihello.sources.catalog()``,
  grouped by namespace, with the endpoint it comes from and a demo value
* the filter reference in ``docs/templates.md`` - from
  ``pihello.template.filters.catalog()``, between the marker comments
  ``<!-- BEGIN GENERATED: filters -->`` and ``<!-- END GENERATED: filters -->``

Usage::

    uv run python scripts/gen_docs.py           # regenerate
    uv run python scripts/gen_docs.py --check   # exit 1 if anything is stale (CI)
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

from pihello import demo, sources
from pihello.template import filters

ROOT = Path(__file__).resolve().parent.parent
DOCS = ROOT / "docs"
VARIABLES_MD = DOCS / "variables.md"
TEMPLATES_MD = DOCS / "templates.md"

BEGIN_FILTERS = "<!-- BEGIN GENERATED: filters -->"
END_FILTERS = "<!-- END GENERATED: filters -->"
REGENERATE = "Run `uv run python scripts/gen_docs.py` after changing"

#: Filter categories in display order, with their headings.
CATEGORIES = {
    "number": "Numbers",
    "time": "Time",
    "text": "Text",
    "list": "Lists",
    "logic": "Logic",
}

#: Example values that would otherwise change with every release.
STABLE_EXAMPLES = {"pihello.version": '`"2.0.0"`'}

_MISSING = object()
_MAX_EXAMPLE = 40


# --------------------------------------------------------------------------- #
# Helpers                                                                     #
# --------------------------------------------------------------------------- #
def cell(text: str) -> str:
    """Make ``text`` safe inside a Markdown table cell."""
    return text.replace("|", "\\|").replace("\n", " ")


def code(text: str) -> str:
    """``text`` as an inline code span (safe inside a table cell)."""
    fence = "``" if "`" in text else "`"
    pad = " " if text.startswith("`") or text.endswith("`") else ""
    return f"{fence}{pad}{cell(text)}{pad}{fence}"


def lookup(tree: Any, path: str) -> Any:
    """The value at dotted ``path`` (``N`` = the first list item), or ``_MISSING``."""
    current = tree
    for segment in path.split("."):
        key = "0" if segment == "N" else segment
        if isinstance(current, dict):
            if key not in current:
                return _MISSING
            current = current[key]
        elif isinstance(current, list) and key.isdigit() and int(key) < len(current):
            current = current[int(key)]
        else:
            return _MISSING
    return current


def shorten(text: str) -> str:
    return text if len(text) <= _MAX_EXAMPLE else text[: _MAX_EXAMPLE - 1] + "…"


def number(value: float) -> str:
    if value.is_integer():
        return str(int(value))
    text = f"{value:.6g}"
    return f"{value:.0f}" if "e" in text else text


def example(value: Any) -> str:
    """A short, typed rendering of a demo value for the tables."""
    if value is _MISSING:
        return "—"
    if value is None:
        return "`null`"
    if isinstance(value, bool):
        return "`true`" if value else "`false`"
    if isinstance(value, str):
        return code(shorten(json.dumps(value, ensure_ascii=False)))
    if isinstance(value, float):
        return code(number(value))
    if isinstance(value, int):
        return code(str(value))
    if isinstance(value, list):
        if all(isinstance(item, (str, int, float)) for item in value):
            items = [number(i) if isinstance(i, float) else json.dumps(i) for i in value]
            text = "[" + ", ".join(items) + "]"
            if len(text) <= _MAX_EXAMPLE:
                return code(text)
        return code(f"[{len(value)} item{'s' if len(value) != 1 else ''}]")
    if isinstance(value, dict):
        return code(f"{{{len(value)} keys}}")
    return code(str(value))


# --------------------------------------------------------------------------- #
# docs/variables.md                                                           #
# --------------------------------------------------------------------------- #
_VARIABLES_INTRO = """\
# Template variables

<!-- Generated by scripts/gen_docs.py from pihello.sources.catalog() and the demo data;
     do not edit by hand. {regenerate} a variable. -->

Templates read Pi-hole data through dotted **paths** such as `{{queries.total}}`.
The first part of a path is its *namespace*. pihello only calls the API
endpoints whose namespaces a template uses (in parallel), so a short
template is also a fast one.

- **`N`** stands for a list index: `{{top_domains.0.domain}}` is the first
  item, `{{top_domains.-1.domain}}` the last. Filters work on whole lists:
  `{{history|pluck(total)|spark}}`. See [templates.md](templates.md).
- **Types**: `int`, `float`, `str`, `bool`, `timestamp` (unix seconds, use the
  `ago` or `datetime` filter), `list` (of objects), `list[str]`, `list[float]`.
- ***derived*** values are computed by pihello from the endpoint's data.
- **Example** values are pihello's demo data, as shown by `pihello vars --demo`.
  `pihello vars` shows your own Pi-hole's values; `pihello vars --all` also
  lists every list item and any key Pi-hole sends that isn't documented here.
- A value that is unavailable (an older Pi-hole, a `null`, an empty list)
  renders as `?`, or fails with `--strict`. See
  [Missing values](templates.md#missing-values).

Every endpoint below exists in every Pi-hole v6 release. A few *fields* were
added later; their descriptions say so (e.g. "FTL v6.3+"). The exact
per-version differences are recorded in [compatibility.md](compatibility.md).
"""


def _source_by_namespace() -> dict[str, sources.Source]:
    return {ns: source for source in sources.SOURCES for ns in source.namespaces}


def _group_catalog() -> tuple[dict[str, list[sources.VariableInfo]], list[sources.VariableInfo]]:
    """Catalog entries per source name (in catalog order), plus the builtins."""
    by_namespace = _source_by_namespace()
    groups: dict[str, list[sources.VariableInfo]] = {s.name: [] for s in sources.SOURCES}
    builtin: list[sources.VariableInfo] = []
    for info in sources.catalog():
        namespace = info.path.split(".", 1)[0]
        source = by_namespace.get(namespace)
        if source is None:
            builtin.append(info)
        else:
            groups[source.name].append(info)
    return groups, builtin


def _variable_rows(entries: list[sources.VariableInfo], variables: dict[str, Any]) -> list[str]:
    rows = ["| Path | Type | Description | Example |", "| :-- | :-- | :-- | :-- |"]
    for info in entries:
        description = cell(info.description)
        if info.source == "derived":
            description += " *(derived)*"
        value = STABLE_EXAMPLES.get(info.path) or example(lookup(variables, info.path))
        rows.append(f"| {code(info.path)} | `{info.type}` | {description} | {value} |")
    return rows


def _anchor(namespaces: tuple[str, ...]) -> str:
    """GitHub's anchor for a heading listing ``namespaces`` (``## a, b`` → ``a-b``)."""
    return "-".join(ns.lower() for ns in namespaces)


def variables_page() -> str:
    """The Markdown of ``docs/variables.md``."""
    variables = demo.variables()
    groups, builtin = _group_catalog()
    out = [_VARIABLES_INTRO.format(regenerate=REGENERATE).rstrip("\n"), ""]
    out += [
        "## Namespaces",
        "",
        "| Namespace | Endpoint (`GET /api/…`) | Contents |",
        "| :-- | :-- | :-- |",
    ]
    for source in sources.SOURCES:
        names = ", ".join(f"[`{ns}`](#{_anchor(source.namespaces)})" for ns in source.namespaces)
        out.append(f"| {names} | {code(source.endpoint)} | {cell(source.description)} |")
    builtin_names = ("now", "pihello", "pihole")
    names = ", ".join(f"[`{ns}`](#{_anchor(builtin_names)})" for ns in builtin_names)
    out.append(f"| {names} | — (built in) | The current time, pihello's version, the Pi-hole URL |")
    for source in sources.SOURCES:
        title = ", ".join(source.namespaces)
        out += [
            "",
            f"## {title}",
            "",
            f"`GET /api/{source.endpoint}`: {source.description}.",
            "",
            *_variable_rows(groups[source.name], variables),
        ]
    out += [
        "",
        f"## {', '.join(builtin_names)}",
        "",
        "Built in: pihello fills these in without asking Pi-hole (they work with `--demo` too).",
        "",
        *_variable_rows(builtin, variables),
    ]
    return "\n".join(out).rstrip("\n") + "\n"


# --------------------------------------------------------------------------- #
# docs/templates.md: filter reference                                         #
# --------------------------------------------------------------------------- #
def filters_section() -> str:
    """The generated filter reference (without the marker lines)."""
    entries = filters.catalog()
    unknown = sorted({info.category for info in entries} - set(CATEGORIES))
    if unknown:
        raise SystemExit(f"gen_docs.py: add a heading for filter categories {unknown}")
    out = [
        "<!-- Generated by scripts/gen_docs.py from pihello.template.filters.catalog();",
        f"     do not edit by hand. {REGENERATE} a filter. -->",
    ]
    for category, heading in CATEGORIES.items():
        rows = [info for info in entries if info.category == category]
        if not rows:
            continue
        out += [
            "",
            f"### {heading}",
            "",
            "| Filter | Description | Example |",
            "| :-- | :-- | :-- |",
        ]
        out += [
            f"| {code(info.signature)} | {cell(info.description)} | "
            f"{code(info.example) if info.example else ''} |".rstrip()
            for info in rows
        ]
    return "\n".join(out)


def templates_page(current: str) -> str:
    """``current`` (docs/templates.md) with a freshly generated filter reference."""
    begin = current.find(BEGIN_FILTERS)
    end = current.find(END_FILTERS)
    if begin < 0 or end < begin:
        raise SystemExit(
            f"gen_docs.py: {TEMPLATES_MD.relative_to(ROOT)} needs the marker lines "
            f"{BEGIN_FILTERS!r} and {END_FILTERS!r}"
        )
    head = current[: begin + len(BEGIN_FILTERS)]
    tail = current[end:]
    return f"{head}\n{filters_section()}\n{tail}"


# --------------------------------------------------------------------------- #
# Entry point                                                                 #
# --------------------------------------------------------------------------- #
def outputs() -> dict[Path, str]:
    """Every generated file and its expected content."""
    return {
        VARIABLES_MD: variables_page(),
        TEMPLATES_MD: templates_page(TEMPLATES_MD.read_text(encoding="utf-8")),
    }


def main(argv: list[str] | None = None) -> int:
    """Entry point; returns the process exit code."""
    parser = argparse.ArgumentParser(description=(__doc__ or "").split("\n\n")[0])
    parser.add_argument("--check", action="store_true", help="fail if generated docs are stale")
    args = parser.parse_args(argv)

    expected = outputs()
    stale = [
        path
        for path, content in expected.items()
        if not path.exists() or path.read_text(encoding="utf-8") != content
    ]
    if args.check:
        for path in stale:
            sys.stderr.write(f"stale: {path.relative_to(ROOT)}\n")
        if stale:
            sys.stderr.write("run: uv run python scripts/gen_docs.py\n")
            return 1
        return 0
    for path in stale:
        path.write_text(expected[path], encoding="utf-8", newline="\n")
        sys.stdout.write(f"wrote {path.relative_to(ROOT)}\n")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
